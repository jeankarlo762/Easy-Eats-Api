-- Traz do repositório do João (módulo Financeiro e Pagamentos):
--  * tbvenda.cupom_id: cupom aplicado na venda (POST /venda/{id}/cupom)
--  * tbcupom_uso: um registro por uso de cupom, para respeitar os limites
--    de uso total e por cliente
--  * tbmovimentacao_financeira.data_movimentacao: data real do lançamento,
--    base do filtro por período (dt_alteracao nunca era preenchido)
-- Só adiciona colunas/tabelas (nada é removido nem convertido) e é
-- idempotente, como as demais migrações desde o V17_1.

ALTER TABLE tbvenda
    ADD COLUMN IF NOT EXISTS cupom_id integer;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_venda_cupom') THEN
        ALTER TABLE tbvenda
            ADD CONSTRAINT fk_venda_cupom FOREIGN KEY (cupom_id) REFERENCES tbcupom (id);
    END IF;
END $$;

ALTER TABLE tbmovimentacao_financeira
    ADD COLUMN IF NOT EXISTS data_movimentacao timestamp(6) without time zone;

CREATE TABLE IF NOT EXISTS tbcupom_uso (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cupom_id integer NOT NULL REFERENCES tbcupom (id),
    venda_id integer NOT NULL REFERENCES tbvenda (id) ON DELETE CASCADE,
    cliente_id integer REFERENCES tbcliente (id),
    dt_uso timestamp(6) without time zone
);

CREATE INDEX IF NOT EXISTS idx_cupom_uso_cupom ON tbcupom_uso (cupom_id);
CREATE INDEX IF NOT EXISTS idx_cupom_uso_cupom_cliente ON tbcupom_uso (cupom_id, cliente_id);
